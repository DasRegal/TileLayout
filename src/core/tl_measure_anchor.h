/*
 * Концы линеек и деформационных швов, примагниченные к плану, держатся за то,
 * к чему примагничены: к углу или грани стены дома (внутренней, наружной,
 * оси), к углу или грани тела перегородки, к её оси, к краю проёма, к стыку
 * полов в нём, к шву, к трубе, предмету или трапу. Когда их двигают, конец
 * едет с ними — длина линейки
 * остаётся настоящей; а другой конец, лежащий на грани стены или перегородки,
 * скользит по ней — линейка остаётся параллельной себе (под прямым углом к
 * стене — так и стоит).
 *
 * Конец запоминается как «контур предмета, ребро, доля вдоль ребра» до правки
 * и ставится на то же место контура после неё. Конец, не лежащий ни на чём, не
 * трогается; если у контура стало другое число углов — тоже.
 */
#ifndef TL_MEASURE_ANCHOR_H
#define TL_MEASURE_ANCHOR_H

#include "tl_project.h"

typedef struct TlMeasureAnchors TlMeasureAnchors;

TlMeasureAnchors *tl_measure_anchors_remember(TlProject *project);
void tl_measure_anchors_apply(TlProject *project, const TlMeasureAnchors *anchors);
void tl_measure_anchors_free(TlMeasureAnchors *anchors);

/* Длина линейки числом. Если её конец держится за то, что можно сдвинуть (трубу, предмет, трап,
   проём, стык в проёме, шов, перегородку), — сдвигается оно, как будто его перетащили мышкой, а
   конец едет с ним; иначе — как tl_ruler_set_length. Двигается тот конец, чей предмет сдвигать
   охотнее: стена дома стоит всегда, перегородка — уступает проёму, а он — трубе, предмету, трапу,
   шву и стыку; поровну — конец. false — длина не подходит. */
bool tl_measure_set_ruler_length(TlProject *project, TlRuler *ruler, double length);

#endif
